#!/usr/bin/env python3
"""Import Omarchy themes: embed each allowed colors.toml, optionally build
Omarchy-layout theme folders (with allowed wallpapers) for a PC or VM.

    python3 scripts/import_omarchy_themes.py [--out DIR] [--selftest]
"""
import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = [Path('/usr/share/omarchy/themes'), Path.home() / '.config/omarchy/themes']
SKIP_PREFIXES = ('chatgpt-image-', 'wallhaven-')
SKIP_NAMES = {'matt1', 'atelier-theme'}
# Wallpapers that show branding icons.
BANNED = {'neon-ridge': ('01-', '02-', '03-')}
VALID = re.compile(r'[a-z0-9-]{1,64}')


def skipped(name):
    return name in SKIP_NAMES or name.startswith(SKIP_PREFIXES)


def banned_wallpaper(theme, file):
    return file.startswith(BANNED.get(theme, ()))


def strip_comments(text):
    return ''.join(l for l in text.splitlines(True) if l.strip() and not l.lstrip().startswith('#'))


def label(name):
    return ' '.join(w[:1].upper() + w[1:] for w in name.split('-'))


def selftest():
    assert skipped('chatgpt-image-aug-23-x')
    assert skipped('wallhaven-d4v2pn')
    assert skipped('matt1')
    assert not skipped('neon-ridge')
    assert banned_wallpaper('neon-ridge', '02-peak.jpg')
    assert not banned_wallpaper('neon-ridge', '10-wallpaper.png')
    assert not banned_wallpaper('nord', '01-x.png')
    assert strip_comments('# a\nx = "#000000"\n') == 'x = "#000000"\n'
    assert label('alpenglow-night') == 'Alpenglow Night'
    print('selftest ok')


def themes():
    found = {}
    for source in SOURCES:
        if not source.is_dir():
            continue
        for folder in sorted(source.iterdir()):
            name = folder.name
            if skipped(name):
                print('skip', name, '(excluded)')
            elif not VALID.fullmatch(name):
                print('skip', name, '(bad id)')
            elif not (folder / 'colors.toml').is_file():
                print('skip', name, '(no colors.toml)')
            else:
                found[name] = folder  # later source wins
    return dict(sorted(found.items()))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--out', type=Path)
    parser.add_argument('--selftest', action='store_true')
    args = parser.parse_args()
    if args.selftest:
        selftest()
        return
    found = themes()
    embedded = ROOT / 'themes/omarchy'
    if embedded.exists():
        shutil.rmtree(embedded)
    embedded.mkdir(parents=True)
    for name, folder in found.items():
        text = strip_comments((folder / 'colors.toml').read_text())
        (embedded / f'{name}.toml').write_text(text)
        if args.out:
            target = args.out / name
            (target / 'backgrounds').mkdir(parents=True, exist_ok=True)
            (target / 'colors.toml').write_text(text)
            backgrounds = folder / 'backgrounds'
            if backgrounds.is_dir():
                for image in sorted(backgrounds.iterdir()):
                    if image.is_file() and not banned_wallpaper(name, image.name):
                        shutil.copyfile(image, target / 'backgrounds' / image.name)
    order = sorted(found, key=lambda n: (n != 'neon-ridge', n))
    lines = ['// Generated by scripts/import_omarchy_themes.py; do not edit.', '',
             '/// (id, label) of every embedded theme, Neon Ridge first.',
             'pub(crate) const NAMES: &[(&str, &str)] = &[']
    lines += [f'    ("{n}", "{label(n)}"),' for n in order]
    lines += ['];', '', '/// (id, colors.toml text) of every embedded theme.',
              'pub(crate) const FILES: &[(&str, &str)] = &[']
    lines += [f'    ("{n}", include_str!("../themes/omarchy/{n}.toml")),' for n in found]
    lines += ['];', '']
    (ROOT / 'src/omarchy_themes.rs').write_text('\n'.join(lines))
    print(len(found), 'themes')


if __name__ == '__main__':
    sys.exit(main())
